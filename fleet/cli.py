"""CLI for the Fleet & Asset Inspection demonstration.

One command from a clean checkout:

    python3 -m fleet demo

It writes the generated photos, the comparison JSON, one PDF page per asset and
the fleet summary into ``out/``. ``verify`` reruns the acceptance checks and exits
non-zero if any fail.
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

from .build import DEFAULT_DATA, DemoResult, build, load, report_payload
from .photos import PhotoStore
from .verify import format_checks, run_checks

REPO_ROOT = Path(__file__).resolve().parent.parent


def _parse_now(value: str | None) -> datetime | None:
    if value is None:
        return None
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as exc:
        raise SystemExit(f"--now: {value!r} is not an ISO 8601 timestamp ({exc})")
    if parsed.tzinfo is None:
        raise SystemExit("--now must include a UTC offset, e.g. 2026-11-15T12:00:00-05:00")
    return parsed


def _summary(result: DemoResult) -> str:
    report = result.report
    stats = report.stats
    lines = [
        f"period {report.period.id} — {report.period.label}",
        f"assets {stats.assets_total} · inspections {len(result.registry.inspections)} · "
        f"photos {len(result.manifest)} · templates {len(result.registry.templates)}",
        f"compared {stats.comparable_assets} · not inspected {stats.not_inspected_assets}",
        f"findings {stats.findings_total} · resolved {stats.findings_resolved} · "
        f"needs review {stats.findings_needs_review}",
        f"new damage {stats.new_damage} · existing damage {stats.existing_damage} · "
        f"newly unroadworthy {stats.newly_unroadworthy}",
        "",
    ]
    for comparison in report.comparisons:
        label = comparison.asset.id
        items = ", ".join(f.item_id for f in comparison.new_damage) or "none"
        lines.append(
            f"  {label:<9} {comparison.recommended_status:<20} "
            f"new damage: {items}"
        )
    for entry in report.not_inspected:
        lines.append(f"  {entry.asset.id:<9} NOT INSPECTED        {entry.reason}")
    lines.extend(
        [
            "",
            f"reports written to {result.out_dir / 'reports'} ({len(result.rendered)} PDFs, one page each)",
            f"comparison data {result.out_dir / 'comparison.json'}",
            f"photo evidence  {result.out_dir / 'photos'} (SHA-256 in photos_manifest.json)",
        ]
    )
    return "\n".join(lines)


def cmd_demo(args: argparse.Namespace) -> int:
    now = _parse_now(args.now)
    result = build(data_dir=Path(args.data), out_dir=Path(args.out), now=now)
    print("Fleet & Asset Inspection — demonstration run")
    print("=" * 62)
    print(_summary(result))
    comparison = result.report.comparison_for("TRL-1042")
    named = len(comparison.new_damage) if comparison else 0
    print()
    print(
        f"acceptance: TRL-1042 pre-use passes, post-use fails {named} named items and all are reported "
        f"with photo evidence; {result.report.stats.not_inspected_assets} assets are in the not-inspected list"
    )
    print("prove it: python3 -m fleet verify")
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    now = _parse_now(args.now)
    result = build(data_dir=Path(args.data), out_dir=Path(args.out), now=now)
    checks = run_checks(result)
    print(format_checks(checks))
    print()
    print(f"artefacts: {result.out_dir / 'reports'}")
    return 0 if all(check.ok for check in checks) else 1


def cmd_stats(args: argparse.Namespace) -> int:
    result = build(data_dir=Path(args.data), out_dir=Path(args.out), now=_parse_now(args.now))
    stats = report_payload(result)["stats"]
    print("regenerated by: python3 -m fleet stats")
    for key, value in stats.items():
        print(f"{key}: {value}")
    print(f"inspections: {len(result.registry.inspections)}")
    print(f"templates: {len(result.registry.templates)}")
    print(f"photos: {len(result.manifest)}")
    print(f"reports: {len(result.rendered)}")
    return 0


def cmd_compare(args: argparse.Namespace) -> int:
    result = build(data_dir=Path(args.data), out_dir=Path(args.out), now=_parse_now(args.now), write=args.write)
    if args.json:
        import json

        print(json.dumps(report_payload(result), indent=2))
        return 0
    print(_summary(result))
    return 0


def cmd_photos(args: argparse.Namespace) -> int:
    registry = load(Path(args.data))
    store = PhotoStore(Path(args.out) / "photos")
    manifest = store.generate_all(registry)
    print(f"generated {len(manifest)} synthetic photos into {store.root}")
    for photo_id in sorted(manifest):
        print(f"  {photo_id}  {manifest[photo_id]['sha256']}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python3 -m fleet",
        description="Fleet & Asset Inspection (DVIR) demonstration — compare pre-use and post-use condition.",
    )
    parser.add_argument("--data", default=str(DEFAULT_DATA), help="seed data directory (default: data/)")
    sub = parser.add_subparsers(dest="command", required=True)

    for name, help_text in (
        ("demo", "generate photos, comparison, one-page PDFs and evidence"),
        ("verify", "run the acceptance checks against the generated artefacts"),
        ("stats", "print the counts the README cites"),
        ("photos", "generate the synthetic photo evidence only"),
    ):
        command = sub.add_parser(name, help=help_text)
        command.add_argument("--out", default=str(Path.cwd() / "out"), help="output directory (default: ./out)")
        command.add_argument("--now", default=None, help="fixed ISO timestamp for reproducible output")
        if name == "demo":
            command.set_defaults(func=cmd_demo)
        elif name == "verify":
            command.set_defaults(func=cmd_verify)
        elif name == "stats":
            command.set_defaults(func=cmd_stats)
        else:
            command.set_defaults(func=cmd_photos)

    compare = sub.add_parser("compare", help="print the comparison summary, or the full JSON")
    compare.add_argument("--out", default=str(Path.cwd() / "out"))
    compare.add_argument("--now", default=None)
    compare.add_argument("--json", action="store_true", help="print the full comparison JSON")
    compare.add_argument("--write", action="store_true", help="also write out/ artefacts")
    compare.set_defaults(func=cmd_compare)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
