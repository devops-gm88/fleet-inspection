"""The one command must work, write the promised artefacts and pass verification."""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
import unittest
from datetime import datetime
from pathlib import Path

from fleet.cli import main

REPO = Path(__file__).resolve().parent.parent
NOW = "2026-11-15T12:00:00-05:00"


class CliTests(unittest.TestCase):
    def test_demo_writes_all_artefacts(self):
        with tempfile.TemporaryDirectory(prefix="fleet-cli-") as temp:
            code = main(["demo", "--out", temp, "--now", NOW])
            self.assertEqual(code, 0)
            out = Path(temp)
            reports = sorted((out / "reports").glob("*.pdf"))
            self.assertEqual(len(reports), 8, [p.name for p in reports])
            self.assertTrue((out / "comparison.json").exists())
            self.assertTrue((out / "photos_manifest.json").exists())
            self.assertTrue((out / "SUMMARY.txt").exists())
            photos = sorted((out / "photos").glob("*.png"))
            self.assertEqual(len(photos), 12)

    def test_verify_passes(self):
        with tempfile.TemporaryDirectory(prefix="fleet-verify-") as temp:
            self.assertEqual(main(["verify", "--out", temp, "--now", NOW]), 0)

    def test_module_entry_point_runs(self):
        with tempfile.TemporaryDirectory(prefix="fleet-module-") as temp:
            env = {**os.environ, "PYTHONPATH": str(REPO)}
            completed = subprocess.run(
                [sys.executable, "-m", "fleet", "demo", "--out", temp, "--now", NOW],
                cwd=REPO,
                env=env,
                capture_output=True,
                text=True,
                timeout=120,
            )
            self.assertEqual(completed.returncode, 0, completed.stderr)
            self.assertIn("Fleet & Asset Inspection", completed.stdout)
            self.assertIn("prove it: python3 -m fleet verify", completed.stdout)

    def test_stats_command(self):
        with tempfile.TemporaryDirectory(prefix="fleet-stats-") as temp:
            completed = subprocess.run(
                [sys.executable, "-m", "fleet", "stats", "--out", temp, "--now", NOW],
                cwd=REPO,
                capture_output=True,
                text=True,
                timeout=120,
            )
            self.assertEqual(completed.returncode, 0, completed.stderr)
            self.assertIn("assets_total: 7", completed.stdout)
            self.assertIn("new_damage: 5", completed.stdout)
            self.assertIn("regenerated by: python3 -m fleet stats", completed.stdout)


if __name__ == "__main__":
    unittest.main()
